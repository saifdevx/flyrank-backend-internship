    ("Widget management: authenticated CRUD; requests without valid auth are rejected",
     [W + "test_admin_api_rejects_missing_or_wrong_key", W + "test_widget_crud_with_correct_status_codes", W + "test_widget_validation_returns_400_with_field_names"]),
    ("Widget management: multi-tenant isolation (tenant A cannot read or modify tenant B's widgets or submissions)",
     [W + "test_tenant_isolation"]),
    ("Widget delivery: embed snippet generated per widget", [W + "test_embed_snippet_is_one_script_tag"]),
    ("Widget delivery: public config endpoint, small payload, correct HTTP cache headers",
     [W + "test_public_config_has_cache_headers_and_etag", W + "test_head_requests_work_on_public_assets"]),
    ("Widget delivery: widget JavaScript served as a versioned bundle", [W + "test_widget_script_is_versioned_and_cached_for_a_year"]),
    ("Public submission API: CORS headers correct, preflight (OPTIONS) handled", [P + "test_cors_preflight_and_headers"]),
    ("Public submission API: malformed and oversized payloads rejected with 4xx JSON errors, never 500 (PROBE 2)",
     [P + "test_probe2_malformed_and_oversized_payloads_get_clean_4xx_never_500", P + "test_unexpected_routes_return_json_errors"]),
    ("Public submission API: valid submissions stored, linked to the right widget and tenant, visible in the dashboard (PROBE 1)",
     [P + "test_probe1_valid_cross_origin_submission_is_stored_and_in_dashboard"]),
    ("Abuse protection: rate limiting returns 429 under a burst and the service keeps serving (PROBE 3)",
     [P + "test_probe3_burst_gets_429_and_service_recovers", P + "test_per_widget_limit"]),
    ("Abuse protection: spam control (honeypot) blocks a spam submission (PROBE 6)", [P + "test_probe6_honeypot_blocks_bots_silently"]),
    ("Enrichment: geo fallback chain. Provider A down -> B answers; both down -> stored anyway without geo (PROBE 4)",
     [P + "test_probe4_geo_fallback_chain"]),
    ("Safe side effects: a failing email/webhook does not prevent the submission being stored (PROBE 5)",
     [P + "test_probe5_failing_side_effect_never_blocks_the_submission", P + "test_job_that_fails_once_is_retried_and_succeeds", P + "test_background_job_sends_notification_when_email_works"]),
