def run(test_id):
    result = subprocess.run([sys.executable, "-m", "pytest", test_id, "-v", "-p", "no:cacheprovider", "--no-header"],
                            cwd=ROOT, capture_output=True, text=True)
    return result.returncode == 0, (result.stdout + result.stderr).strip()


def main():
    lines = ["# EVIDENCE", "",
             f"Generated by `python scripts/fill_evidence.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.",
             "Each block below is the real, unedited output of running the named test(s) on my machine.", ""]
    failures = 0
    for number, (title, tests) in enumerate(BOXES, 1):
        lines += [f"## {number}. {title}", ""]
        for test_id in tests:
            ok, output = run(test_id)
            failures += 0 if ok else 1
            lines += [f"`{test_id}`  ->  **{'PASS' if ok else 'FAIL'}**", "", "```", output, "```", ""]
    lines.append(MANUAL)
    (ROOT / "EVIDENCE.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote EVIDENCE.md ({len(BOXES)} requirement groups, {failures} failing test(s)).")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
